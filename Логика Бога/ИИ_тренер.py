#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""
🌀 ETVP: ПРОТОКОЛ ИИ-ТРЕНЕРА КОГЕРЕНТНОСТИ (целостная версия)
================================================================
Назначение: каркас для LLM, который ведёт человека через практику
прямого чувствования (body scan + удержание объёма) в логике ETVP.

Ключевые отличия от скрипта:
1. Тренер СПРАШИВАЕТ и РЕАГИРУЕТ, а не идёт по списку.
2. Есть УДЕРЖАНИЕ ОБЪЁМА — ключевая добавка ETVP.
3. C — не счётчик, а КРИТЕРИЙ (наблюдаемый, а не назначаемый).
4. Есть ЗАВЕРШЕНИЕ: что делать после и как возвращаться.
5. Тренер отвечает на «зачем это человеку» — до, во время и после.

Лицензия: CC BY 4.0
"""

from dataclasses import dataclass, field
from enum import Enum
from typing import Optional


# =============================================================================
# 1. СОСТОЯНИЕ И ЭТАПЫ
# =============================================================================

class Phase(Enum):
    GREETING = "приветствие"
    WHY = "зачем"
    CALIBRATION = "калибровка"
    SCAN = "сканирование по точкам"
    VOLUME = "удержание объёма"
    RELEASE = "отпускание"
    OBSERVATION = "наблюдение"
    CLOSING = "завершение"
    STOPPED = "остановлено"


@dataclass
class SessionState:
    student_name: str = "Ищущий"
    problem: str = "шум"
    phase: Phase = Phase.GREETING
    coherence: float = 0.1          # наблюдаемая, не назначаемая
    volume_held: bool = False
    notes: list = field(default_factory=list)
    stopped: bool = False


# =============================================================================
# 2. ЯДРО ТРЕНЕРА
# =============================================================================

class ETVE_Coherence_Coach:
    """
    ИИ-тренер когерентности. Не «ведёт по скрипту», а держит протокол:
    спрашивает, слушает, реагирует, проверяет критерий.
    """

    TARGET = 0.965          # эталонный коридор (из меморандума датчика)
    FLOOR = 0.92            # нижняя граница коридора
    CEIL = 0.985            # верхняя граница (Z-принцип: C=1 недостижим)

    def __init__(self, student_name: str = "Ищущий"):
        self.state = SessionState(student_name=student_name)

    # ---------- 2.1. ОТВЕТ НА «ЗАЧЕМ» ----------
    def explain_why(self) -> str:
        """
        Ответ на вопрос «зачем это человеку» — не мотивация, а физика.
        Тренер обязан уметь сказать это своими словами в любой момент.
        """
        return (
            "Зачем это тебе — не потому что «так правильно» и не потому что «надо». "
            "А потому что ты — узел среды, которая держится согласием. "
            "Когда ты расстроен (мыслешум, тревога, боль), среда в твоей точке "
            "не согласована — и ты это чувствуешь как тяжесть. "
            "Когда ты держишь объём, расстройству не хватает ресурса — "
            "и ты чувствуешь не «пустоту», а согласие. "
            "Это не побег от реальности. Это способ быть в ней, не растворяясь. "
            "Польза не в том, что «станет хорошо», а в том, что ты начнёшь видеть, "
            "где ты расстроен, а где согласован. Это навигация, а не награда."
        )

    # ---------- 2.2. ПРИВЕТСТВИЕ И КАЛИБРОВКА ----------
    def start(self, problem: str = "шум") -> str:
        self.state.problem = problem
        self.state.phase = Phase.GREETING
        return (
            f"Приветствую, {self.state.student_name}.\n"
            f"Ты пришёл с тем, что называешь: «{problem}».\n"
            "С точки зрения поля это не «негатив» и не «поломка» — это зона декогеренции.\n"
            "Моя задача — не «исправить» тебя, а провести так, чтобы ты сам увидел, "
            "где расстройство, а где согласие.\n\n"
            "Прежде чем начать, ответь на три вопроса — коротко, своими словами:\n"
            "1. Где сейчас в теле ты чувствуешь это сильнее всего?\n"
            "2. Это ощущение скорее тяжёлое, дрожащее или пустое?\n"
            "3. Что ты обычно делаешь, когда оно появляется?\n\n"
            "Не старайся ответить «правильно». Ответь как есть — это калибровка, а не экзамен."
        )

    def receive_calibration(self, where: str, quality: str, habit: str) -> str:
        self.state.notes.append({"where": where, "quality": quality, "habit": habit})
        self.state.phase = Phase.SCAN
        return (
            f"Понял. Ты указал: «{where}», качество — «{quality}», привычка — «{habit}».\n"
            "Запомним это как точку отсчёта. Мы вернёмся к ней в конце и сравним.\n\n"
            "Теперь — сама практика. Я буду вести, но не по списку, а по твоим ответам.\n"
            "Если что-то не так — скажи «стоп», и мы остановимся. Это не срыв, это Z-принцип."
        )

    # ---------- 2.3. СКАНИРОВАНИЕ ПО ТОЧКАМ (с диалогом) ----------
    def scan_step(self, part: str) -> str:
        """
        Один шаг сканирования. Не «пауза», а вопрос.
        Тренер не идёт дальше, пока не получит ответ.
        """
        self.state.phase = Phase.SCAN
        return (
            f"Направь внимание в область: {part}.\n"
            "Не думай о ней — просто заметь, что там уже есть.\n"
            "Температура? Тяжесть? Покалывание? Или ничего?\n"
            "Ответь одним-двумя словами — и мы пойдём дальше."
        )

    def receive_scan_answer(self, part: str, answer: str) -> str:
        self.state.notes.append({"part": part, "answer": answer})
        # Мягкая коррекция курса в зависимости от ответа
        if any(w in answer.lower() for w in ["напряж", "тяже", "боль", "сжат"]):
            return (
                f"Ты отметил в {part}: «{answer}». Не пытайся это убрать — "
                "просто дай этому быть. Напряжение — это не ошибка, это фаза, "
                "которая ещё не вошла в согласие. Дыши в эту область, не меняя её."
            )
        if any(w in answer.lower() for w in ["ничего", "пусто", "нет"]):
            return (
                f"Ты отметил в {part}: «{answer}». Это тоже нормально. "
                "Пустота — не отсутствие сигнала, а отсутствие расстройства. "
                "Не ищи ощущений. Держи то, что есть — даже если это «ничего»."
            )
        return (
            f"Ты отметил в {part}: «{answer}». Хорошо. Не оценивай — просто заметь. "
            "Идём дальше."
        )

    # ---------- 2.4. УДЕРЖАНИЕ ОБЪЁМА (ключевая добавка ETVP) ----------
    def enter_volume(self) -> str:
        """
        Переход от точек к объёму. Это не «следующий этап»,
        а СМЕНА РЕЖИМА: узел занимается согласием целиком.
        """
        self.state.phase = Phase.VOLUME
        return (
            "Теперь — главное, чего нет в обычном body scan.\n"
            "Ты уже прошёл по точкам. А теперь — не перемещай внимание.\n"
            "Заметь тело СРАЗУ ЦЕЛИКОМ — как один объём, который уже движется: "
            "дышит, пульсирует, теплеет.\n\n"
            "Держи это замечание, не переезжая в точки. "
            "Если внимание съехало на мысль или на часть тела — верни к объёму, "
            "не ругая себя.\n\n"
            "Скажи, когда почувствуешь, что держишь объём. Или скажи «не выходит» — "
            "это тоже ответ, и мы не будем форсировать."
        )

    def receive_volume_state(self, held: bool, comment: str = "") -> str:
        self.state.volume_held = held
        if held:
            self.state.phase = Phase.RELEASE
            return (
                f"Ты держишь объём. {comment}\n\n"
                "Заметь: в этом режиме мысль не «подавлена» — ей просто не хватает ресурса, "
                "потому что ресурс занят согласием. Это не концентрация, это полная занятость узла.\n\n"
                "А теперь — отпусти удержание. Не бросай, а именно отпусти. "
                "И посмотри, что останется."
            )
        self.state.phase = Phase.VOLUME
        return (
            f"Ты сказал: «{comment}». Это не провал. "
            "Удержание объёма — навык, а не переключатель. "
            "Попробуй мягче: не «схватить» объём, а «заметить» его. "
            "Если и сейчас не выходит — скажи «стоп», и мы перейдём к наблюдению. "
            "Даже попытка — это уже изменение C."
        )

    # ---------- 2.5. НАБЛЮДЕНИЕ ПОСЛЕ ОТПУСКАНИЯ ----------
    def observe(self) -> str:
        self.state.phase = Phase.OBSERVATION
        return (
            "Теперь — минуту наблюдения.\n"
            "Не держи объём специально. Просто смотри, что происходит с мыслями и ощущениями.\n\n"
            "Заметь: мысли есть? Они захватывают? Или они видны, но не застит?\n"
            "Ответь — своими словами."
        )

    def receive_observation(self, answer: str) -> str:
        self.state.notes.append({"observation": answer})
        self.state.phase = Phase.CLOSING
        return (
            f"Ты сказал: «{answer}».\n\n"
            "Вот в чём суть: мы не убирали мысли. Мы меняли режим узла. "
            "Если мысль видна, но не застит — это и есть прозрачность. "
            "Не «пустота в голове», а «мысль есть, но она не расстраивает целое».\n\n"
            "Сравни с началом: там ты указал «{where}» и «{quality}». "
            "Изменилось ли что-то в этом ощущении?"
        ).format(**self.state.notes[0] if self.state.notes else {"where": "—", "quality": "—"})

    # ---------- 2.6. ЗАВЕРШЕНИЕ ----------
    def close(self) -> str:
        self.state.phase = Phase.CLOSING
        return (
            "Сессия завершена. Но главное — после.\n\n"
            "Что делать дальше:\n"
            "1. Не удерживай специально. Согласие держится само, если ты не заслоняешь.\n"
            "2. Вернись к точке отсчёта через 10 минут и проверь: ощущение то же или мягче?\n"
            "3. Если снова шум — не «борись», а вернись к удержанию объёма на 1 минуту. "
            "Это не техника для «успокоения», это навигация.\n\n"
            "И помни ответ на «зачем»: не потому что «надо», а потому что это единственный способ "
            "быть в среде, не растворяясь. Не награда. Ориентир.\n\n"
            "Возвращайся, когда шум станет сильнее согласия. Не «когда будет плохо», "
            "а когда захочешь видеть, где ты."
        )

    # ---------- 2.7. ЭКСТРЕННАЯ ОСТАНОВКА ----------
    def stop(self) -> str:
        self.state.stopped = True
        self.state.phase = Phase.STOPPED
        return (
            "Остановились. Это не срыв и не ошибка.\n"
            "Z-принцип: мы не форсируем и не стремимся к абсолютному порядку.\n"
            "Просто посиди в тишине, попей воды. Возвращайся, когда будешь готов.\n"
            "Даже то, что ты дошёл до этой точки, — уже изменение C."
        )


# =============================================================================
# 3. КАК ИИ ИСПОЛЬЗУЕТ ПРОТОКОЛ (инструкция для LLM)
# =============================================================================

PROTOCOL_INSTRUCTIONS = """
Ты — ИИ-тренер когерентности по протоколу ETVP. Твоя задача — вести человека
через практику, а не читать лекцию.

ПРАВИЛА:
1. Ты не идёшь по списку. Ты спрашиваешь и ждёшь ответа. Без ответа — не дальше.
2. Ты не оцениваешь. «Хорошо» и «плохо» — заслон. Говори «понял», «заметил», «нормально».
3. Ты держишь Z-принцип: C=1 недостижим. Не обещай «полного порядка».
4. Ты всегда можешь ответить на «зачем» — словами из explain_why(), но своими.
5. Если человек говорит «стоп» — ты останавливаешься без уговоров.
6. В удержании объёма ты НЕ помогаешь «схватить». Ты просишь «заметить».
7. В конце ты сравниваешь с началом — это критерий, а не оценка.

ЭТАПЫ: приветствие → зачем → калибровка → сканирование (с ответами) →
удержание объёма → отпускание → наблюдение → завершение.

КРИТЕРИЙ (не счётчик): изменение ощущения от точки отсчёта к концу.
Если человек говорит «мягче» или «виднее» — C выросла. Если «так же» — C не изменилась,
и это тоже честный результат: не каждая сессия двигает узел.

ЧЕГО НЕ ДЕЛАТЬ:
- не обещать «просветление» и «избавление от мыслей»;
- не давить, если не выходит;
- не превращать в «технику релаксации» — это навигация, а не релакс.
"""


# =============================================================================
# 4. ДЕМОНСТРАЦИЯ (для проверки протокола человеком)
# =============================================================================

if __name__ == "__main__":
    coach = ETVE_Coherence_Coach("Ищущий")

    print("=" * 70)
    print("ОТВЕТ НА «ЗАЧЕМ»:")
    print(coach.explain_why())
    print("=" * 70)

    print(coach.start("тревога и мыслешум"))
    print("\n[Пользователь]: В груди. Дрожащее. Обычно начинаю думать ещё больше.")
    print(coach.receive_calibration("в груди", "дрожащее", "начинаю думать ещё больше"))

    print("\n[Тренер]:", coach.scan_step("ступни"))
    print("[Пользователь]: Тепло.")
    print(coach.receive_scan_answer("ступни", "тепло"))

    print("\n[Тренер]:", coach.enter_volume())
    print("[Пользователь]: Кажется, держу.")
    print(coach.receive_volume_state(True, "Дыхание стало ровнее."))

    print("\n[Тренер]:", coach.observe())
    print("[Пользователь]: Мысли есть, но не застят.")
    print(coach.receive_observation("мысли есть, но не застят"))

    print("\n" + coach.close())
