#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""
🌀 ETVP: Поиск порога воли
================================================================================
Логика поля: фиксация = акт воли · условия.
Акт не выводится. Но условия (порог) — можно найти.

Ищем: при каком C_оп фиксация меняется скачком?
================================================================================
"""

import numpy as np

# =============================================================================
# 0. БАЗИС
# =============================================================================

PHI = (1.0 + np.sqrt(5.0)) / 2.0
C_FFS = 0.87
S_CYCLE = 0.12
SIGMA = 0.001

# =============================================================================
# 1. ДАННЫЕ
# =============================================================================

C_op_values = np.linspace(0.1, 1.0, 50)
n_values = [3, 4, 5, 6, 7, 8]
S_values = [0.05, 0.10, 0.12, 0.20, 0.30]

# =============================================================================
# 2. ФИКСАЦИЯ (без воли, только условия)
# =============================================================================

def fixation_conditions(C_op, n, S):
    """Фиксация как функция условий."""
    holding = C_op * n
    noise = abs(S - S_CYCLE) + SIGMA
    return holding / noise

# =============================================================================
# 3. ПОИСК ПОРОГА
# =============================================================================

print("=" * 80)
print("🌀 ETVP: Поиск порога воли")
print("=" * 80)

# Считаем фиксацию для разных C_оп при фиксированных n, S
print("\n📊 Фиксация vs C_оп (n = 5, S = 0.12):")
print(f"{'C_оп':<8} {'Фиксация':<12} {'Δ':<12}")
print("-" * 32)

prev = None
for C_op in C_op_values:
    f = fixation_conditions(C_op, 5, 0.12)
    delta = f - prev if prev is not None else 0
    print(f"{C_op:<8.2f} {f:<12.3f} {delta:<12.3f}")
    prev = f

# Поиск скачка
print("\n📊 Поиск скачка (n = 5, S = 0.12):")
fixations = [fixation_conditions(C_op, 5, 0.12) for C_op in C_op_values]
deltas = np.diff(fixations)
max_delta_idx = np.argmax(np.abs(deltas))
print(f"  Максимальный скачок при C_оп = {C_op_values[max_delta_idx]:.4f}")
print(f"  Δ = {deltas[max_delta_idx]:.6f}")

# Проверка зависимости порога от n
print("\n📊 Зависимость порога от n (S = 0.12):")
for n in n_values:
    fixations = [fixation_conditions(C_op, n, 0.12) for C_op in C_op_values]
    deltas = np.diff(fixations)
    max_delta_idx = np.argmax(np.abs(deltas))
    print(f"  n = {n}: порог при C_оп = {C_op_values[max_delta_idx]:.4f}, Δ = {deltas[max_delta_idx]:.6f}")

# Проверка зависимости порога от S
print("\n📊 Зависимость порога от S (n = 5):")
for S in S_values:
    fixations = [fixation_conditions(C_op, 5, S) for C_op in C_op_values]
    deltas = np.diff(fixations)
    max_delta_idx = np.argmax(np.abs(deltas))
    print(f"  S = {S:.2f}: порог при C_оп = {C_op_values[max_delta_idx]:.4f}, Δ = {deltas[max_delta_idx]:.6f}")

# =============================================================================
# 4. ПРОВЕРКА ГИПОТЕЗЫ: ПОРОГ = 0.8
# =============================================================================

print("\n📊 Проверка гипотезы: порог = 0.8")
print(f"  Фиксация при C_оп = 0.8, n = 5, S = 0.12: {fixation_conditions(0.8, 5, 0.12):.3f}")
print(f"  Фиксация при C_оп = 0.7, n = 5, S = 0.12: {fixation_conditions(0.7, 5, 0.12):.3f}")
print(f"  Фиксация при C_оп = 0.9, n = 5, S = 0.12: {fixation_conditions(0.9, 5, 0.12):.3f}")

# =============================================================================
# 5. ЧЕРЕЗ Φ
# =============================================================================

print("\n📊 Порог через Φ:")
print(f"  1 − 1/Φ⁵ = {1 - 1/PHI**5:.6f}")
print(f"  1 − 1/Φ⁴ = {1 - 1/PHI**4:.6f}")
print(f"  Φ/(Φ+1/Φ²) = {PHI/(PHI + 1/PHI**2):.6f}")

print("\n✅ Поиск завершён.")
