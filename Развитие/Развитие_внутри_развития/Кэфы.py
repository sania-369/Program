# =============================================================================
# ПОИСК КОМБИНАЦИЙ ДЛЯ КАЖДОГО ЦЕЛЕВОГО ЧИСЛА
# =============================================================================
def find_combinations(target, max_terms=3):
    """Ищет комбинации базовых чисел, дающие target."""
    results = []
    names = list(base_numbers.keys())
    vals = [base_numbers[n] for n in names]
    
    # 1. Одиночные числа
    for i, v in enumerate(vals):
        if abs(v - target) < 1e-9:
            results.append((f"{names[i]}", v))
    
    # 2. Суммы и разности двух чисел
    for i, j in combinations(range(len(vals)), 2):
        if abs(vals[i] + vals[j] - target) < 1e-9:
            results.append((f"{names[i]} + {names[j]}", vals[i] + vals[j]))
        if abs(vals[i] - vals[j] - target) < 1e-9:
            results.append((f"{names[i]} - {names[j]}", vals[i] - vals[j]))
        if abs(vals[j] - vals[i] - target) < 1e-9:
            results.append((f"{names[j]} - {names[i]}", vals[j] - vals[i]))
    
    # 3. Произведения и отношения двух чисел
    for i, j in combinations(range(len(vals)), 2):
        if abs(vals[i] * vals[j] - target) < 1e-9:
            results.append((f"{names[i]} * {names[j]}", vals[i] * vals[j]))
        if abs(vals[j]) > 1e-9 and abs(vals[i] / vals[j] - target) < 1e-9:
            results.append((f"{names[i]} / {names[j]}", vals[i] / vals[j]))
        if abs(vals[i]) > 1e-9 and abs(vals[j] / vals[i] - target) < 1e-9:
            results.append((f"{names[j]} / {names[i]}", vals[j] / vals[i]))
    
    return results

